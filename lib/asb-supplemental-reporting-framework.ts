export type AsbSupplementalReportingItem =
  (typeof ASB_SUPPLEMENTAL_REPORTING_FRAMEWORK)[number];

export const ASB_SUPPLEMENTAL_REPORTING_RULES = `SUPPLEMENTAL PRE-K GOLD / ATL REPORTING LENS
- This is a private, school-specific draft vocabulary source. It is not the active assessment framework.
- Use it only when direct learner evidence clearly supports a more precise description or a proportionate next step than the main crosswalk provides.
- It must never create or change an observation match, developmental level, star, baseline, snapshot, heat-map count or attainment judgment.
- The active GOLD crosswalk and direct observations remain authoritative. A supplemental statement cannot override or upgrade them.
- Do not assume that a learner has achieved a supplemental statement because it appears here. Preserve support, frequency and uncertainty from the source evidence.
- For a next step, move only one realistic increment beyond the evidenced action. Do not use the four-star wording automatically.
- Do not mention this lens, its draft status, objective numbers, GOLD codes or star placements in family-facing text.`;

const TOKEN_ALIASES: Record<string, string> = {
  balanced: "balance",
  balances: "balance",
  behaviour: "behavior",
  behaviours: "behavior",
  colour: "color",
  colours: "color",
  organise: "organize",
  organised: "organize",
  organising: "organize",
  recognises: "recognize",
  recognising: "recognize",
  recognised: "recognize",
};

const STOP_WORDS = new Set([
  "about", "after", "again", "another", "appropriate", "begins",
  "beginning", "being", "child", "children", "during", "familiar",
  "from", "growing", "increasing", "increasingly", "into", "most",
  "other", "others", "simple", "some", "such", "than", "that",
  "their", "them", "then", "there", "these", "they", "through",
  "using", "when", "where", "while", "with", "words",
]);

function tokens(value: string) {
  return (value.toLowerCase().match(/[a-z0-9]+/g) ?? [])
    .map((token) => TOKEN_ALIASES[token] ?? token)
    .filter((token) => token.length >= 4 && !STOP_WORDS.has(token));
}

export function getRelevantAsbSupplementalReportingItems(
  sourceText: string,
  maximumItems = 12
) {
  const sourceTokens = new Set(tokens(sourceText));

  if (sourceTokens.size === 0 || maximumItems <= 0) return [];

  return ASB_SUPPLEMENTAL_REPORTING_FRAMEWORK.map((item) => {
    const objectiveTokens = Array.from(new Set(tokens(item.objective)));
    const descriptorTokens = Array.from(
      new Set(item.levels.flatMap((level) => tokens(level)))
    );
    const objectiveMatches = objectiveTokens.filter((token) =>
      sourceTokens.has(token)
    ).length;
    const descriptorMatches = descriptorTokens.filter((token) =>
      sourceTokens.has(token)
    ).length;

    return {
      item,
      score: objectiveMatches * 4 + descriptorMatches,
      objectiveMatches,
      descriptorMatches,
    };
  })
    .filter(
      (candidate) =>
        candidate.score >= 4 &&
        (candidate.objectiveMatches >= 2 ||
          (candidate.objectiveMatches >= 1 &&
            candidate.descriptorMatches >= 2) ||
          candidate.descriptorMatches >= 4)
    )
    .sort(
      (first, second) =>
        second.score - first.score ||
        Number(first.item.id) - Number(second.item.id)
    )
    .slice(0, Math.min(20, Math.floor(maximumItems)))
    .map((candidate) => candidate.item);
}
